-- EMTS Oracle schema. Connect as the EMTS schema owner before running.
CREATE TABLE departments (
  department_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(100) NOT NULL UNIQUE,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE users (
  user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR2(80) NOT NULL UNIQUE,
  password_hash VARCHAR2(255) NOT NULL,
  full_name VARCHAR2(150) NOT NULL,
  role VARCHAR2(20) DEFAULT 'EMPLOYEE' NOT NULL CHECK (role IN ('ADMIN','EMPLOYEE')),
  department_id NUMBER REFERENCES departments(department_id),
  phone VARCHAR2(30), email VARCHAR2(150), is_active NUMBER(1) DEFAULT 1 NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE attendance (
  attendance_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id NUMBER NOT NULL REFERENCES users(user_id),
  attendance_date DATE NOT NULL,
  check_in TIMESTAMP, check_out TIMESTAMP,
  status VARCHAR2(20) DEFAULT 'PRESENT' NOT NULL,
  total_working_hours NUMBER(6,2), check_in_latitude NUMBER(10,7), check_in_longitude NUMBER(10,7),
  CONSTRAINT uq_attendance_user_date UNIQUE(user_id, attendance_date)
);
CREATE TABLE employee_tasks (
  task_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR2(180) NOT NULL, description CLOB,
  assignee_id NUMBER NOT NULL REFERENCES users(user_id),
  status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL CHECK(status IN ('PLANNED','PENDING','IN_PROGRESS','COMPLETED')),
  progress NUMBER(3) DEFAULT 0 CHECK(progress BETWEEN 0 AND 100),
  deadline DATE, created_by NUMBER REFERENCES users(user_id), created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE leave_requests (
  leave_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id NUMBER NOT NULL REFERENCES users(user_id),
  start_date DATE NOT NULL, end_date DATE NOT NULL,
  leave_type VARCHAR2(20) NOT NULL CHECK(leave_type IN ('SICK','CASUAL','ANNUAL','MATERNITY','PATERNITY')),
  reason CLOB, status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL CHECK(status IN ('PENDING','APPROVED','REJECTED')),
  reviewed_by NUMBER REFERENCES users(user_id), reviewed_at TIMESTAMP, created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_leave_dates CHECK(end_date >= start_date)
);
CREATE TABLE leave_balances (
  user_id NUMBER PRIMARY KEY REFERENCES users(user_id), casual_remaining NUMBER DEFAULT 10 NOT NULL,
  sick_remaining NUMBER DEFAULT 10 NOT NULL, total_earned NUMBER DEFAULT 20 NOT NULL
);
CREATE TABLE notifications (
  notification_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id NUMBER NOT NULL REFERENCES users(user_id), title VARCHAR2(180) NOT NULL,
  message VARCHAR2(1000), created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  is_read NUMBER(1) DEFAULT 0 NOT NULL
);
CREATE TABLE announcements (
  announcement_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR2(180) NOT NULL, message CLOB, priority VARCHAR2(20) DEFAULT 'NORMAL',
  author_id NUMBER REFERENCES users(user_id), created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE task_logs (
  task_log_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id NUMBER NOT NULL REFERENCES employee_tasks(task_id), user_id NUMBER NOT NULL REFERENCES users(user_id),
  duration_minutes NUMBER NOT NULL, note VARCHAR2(1000), log_date TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE task_activities (
  activity_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id NUMBER NOT NULL REFERENCES employee_tasks(task_id), user_id NUMBER NOT NULL REFERENCES users(user_id),
  message VARCHAR2(1000), activity_type VARCHAR2(30) DEFAULT 'COMMENT', created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE regularization_requests (
  request_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id NUMBER NOT NULL REFERENCES users(user_id), attendance_date DATE NOT NULL,
  reason VARCHAR2(1000) NOT NULL, requested_check_in TIMESTAMP, requested_check_out TIMESTAMP,
  status VARCHAR2(20) DEFAULT 'PENDING' CHECK(status IN ('PENDING','APPROVED','REJECTED')),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, reviewed_by NUMBER REFERENCES users(user_id)
);
CREATE TABLE performance_scores (
  score_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id NUMBER NOT NULL REFERENCES users(user_id), score_month VARCHAR2(7) NOT NULL,
  attendance_score NUMBER(3), task_score NUMBER(3), punctuality_score NUMBER(3), final_score NUMBER(5,2),
  CONSTRAINT uq_performance_user_month UNIQUE(user_id, score_month)
);
CREATE TABLE audit_logs (
  audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id NUMBER REFERENCES users(user_id), action VARCHAR2(180) NOT NULL,
  target_id VARCHAR2(80), details VARCHAR2(2000), created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE system_config (
  config_key VARCHAR2(100) PRIMARY KEY, config_value VARCHAR2(500), updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_attendance_date ON attendance(attendance_date);
CREATE INDEX ix_tasks_assignee ON employee_tasks(assignee_id, status);
CREATE INDEX ix_leaves_status ON leave_requests(status, start_date);
